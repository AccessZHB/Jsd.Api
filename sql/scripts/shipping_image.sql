-- 订单主表 trx_order 增加面单照片字段
ALTER TABLE trx_order
    ADD COLUMN shipping_image_url VARCHAR(500) NULL
    COMMENT '物流面单照片路径（发货时上传，相对路径如 /upload/202610/xxx.jpg）';

